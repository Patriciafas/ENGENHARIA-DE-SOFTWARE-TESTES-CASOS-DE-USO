package matematica;

public class Math {
    
    public int sun(int a, int b){
        return a+b;
    }

    public int sub(int a, int b){
        return a-b;
    }
    public int mult(int a, int b){
        return a*b;
    }
    public float div(int a, int b){
        return a/b;
    }
    
}
